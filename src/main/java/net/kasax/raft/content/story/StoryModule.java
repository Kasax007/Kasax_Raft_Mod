package net.kasax.raft.content.story;

import net.kasax.raft.platform.PayloadTypeRegistry;
import net.kasax.raft.content.ContentModule;
import net.kasax.raft.content.story.net.OpenJournalPayload;
import net.kasax.raft.content.story.net.OpenLogPayload;

/**
 * Beach Craft 3 module "story" (docs/design/beachcraft3.md, sections 3 and 9): the Expedition Journal, letters in
 * bottles, supply barrels, the Tide Sigils and the Tidewarden Key, the Tidewarden and Leviathan altars, the Tide Seal
 * and the sanctum blocks, research terminals and radios. The texts, loot tables and advancements are generated by
 * {@code tools/content/story}.
 */
public class StoryModule implements ContentModule {
    @Override
    public String name() {
        return "story";
    }

    @Override
    public void init() {
        StoryContent.register();
        PayloadTypeRegistry.playS2C().register(OpenJournalPayload.TYPE, OpenJournalPayload.CODEC);
        PayloadTypeRegistry.playS2C().register(OpenLogPayload.TYPE, OpenLogPayload.CODEC);
        StoryEvents.register();
    }

    @Override
    public void initClient() {
        net.kasax.raft.content.story.client.StoryClient.init();
    }
}
