    @Override
    public void setupAnim(SharkRenderState state) {
        super.setupAnim(state);
        float t = state.ageInTicks;
        float move = Mth.clamp(state.walkAnimationSpeed * 2.5F, 0.0F, 1.0F);
        boolean inWater = state.isInWater;
        float freq = inWater ? 0.2F + 0.16F * move : 0.9F;
        float amp = inWater ? 0.16F + 0.22F * move : 0.45F;
        float p = t * freq;

        this.body.xRot = state.xRot * Mth.DEG_TO_RAD;
        // travelling wave from the head to the tail fin
        this.body.yRot = Mth.sin(p) * amp * 0.12F;
        this.head.yRot = -Mth.sin(p + 0.4F) * amp * 0.22F;
        this.tail1.yRot = Mth.sin(p - 0.7F) * amp * 0.65F;
        this.tail2.yRot = Mth.sin(p - 1.4F) * amp * 0.95F;
        float fin = Mth.sin(p - 2.1F) * amp * 0.9F;
        this.tailFinUpper.yRot = fin;
        this.tailFinLower.yRot = fin;
        this.dorsalFin.zRot = Mth.sin(p - 0.3F) * amp * 0.08F;
        // pectoral fins: small steering flutter, raised a little in fast swimming
        float flutter = Mth.sin(t * 0.13F) * 0.07F;
        this.leftFin.zRot += flutter - move * 0.12F;
        this.rightFin.zRot += -flutter + move * 0.12F;
        // jaw: almost closed while cruising, snaps wide open on a bite with the snout lifting
        float bite = state.bite;
        this.jaw.xRot = 0.04F + Mth.sin(t * 0.07F) * 0.02F + bite * 0.8F;
        this.head.xRot = -bite * 0.22F;
        if (!inWater) {
            this.body.zRot = 1.35F;
            this.jaw.xRot += 0.25F;
        }
    }
